CREATE TABLE accounts (
    vpa         VARCHAR(255)   NOT NULL PRIMARY KEY,
    holder_name VARCHAR(255)   NOT NULL,
    balance     NUMERIC(19, 2) NOT NULL,
    version     BIGINT
);

CREATE TABLE transactions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    packet_hash    VARCHAR(64)    NOT NULL,
    sender_vpa     VARCHAR(255)   NOT NULL,
    receiver_vpa   VARCHAR(255)   NOT NULL,
    amount         NUMERIC(19, 2) NOT NULL,
    signed_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    settled_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    bridge_node_id VARCHAR(255)   NOT NULL,
    hop_count      INTEGER        NOT NULL,
    status         VARCHAR(255)   NOT NULL,
    CONSTRAINT chk_transactions_status CHECK (status IN ('SETTLED', 'REJECTED'))
);

-- Idempotency safety net: the same packet can never be recorded twice,
-- even across multiple app instances.
CREATE UNIQUE INDEX idx_packet_hash ON transactions (packet_hash);
CREATE INDEX idx_transactions_id_desc ON transactions (id DESC);
